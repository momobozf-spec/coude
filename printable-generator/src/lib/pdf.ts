// Theme-aware word banks for Islamic educational content
const THEME_WORD_BANK: Record<string, string[]> = {
  ramadan: ["RAMADAN", "FAST", "IFTAR", "SUHOOR", "QURAN", "PRAYER", "MOSQUE", "DATES"],
  eid: ["EID", "SALAH", "GIFTS", "FAMILY", "HAPPY", "MOSQUE", "PRAY", "SHARE"],
  mosque: ["MOSQUE", "MINARET", "DOME", "PRAYER", "WUDU", "IMAM", "QURAN", "SALAH"],
  arabic: ["ALIF", "BA", "TA", "ARABIC", "WRITE", "READ", "LEARN", "LETTER"],
  quran: ["QURAN", "SURAH", "AYAH", "READ", "RECITE", "LEARN", "BOOK", "HAFIZ"],
  kindness: ["KIND", "SHARE", "HELP", "LOVE", "CARE", "GIVE", "SMILE", "FRIEND"],
  patience: ["SABR", "WAIT", "CALM", "PEACE", "TRUST", "HOPE", "PRAY", "FAITH"],
  gratitude: ["SHUKR", "THANKS", "HAPPY", "GIFT", "BLESSED", "PRAISE", "SMILE", "JOY"],
  hajj: ["HAJJ", "KAABA", "MINA", "ARAFAT", "TAWAF", "IHRAM", "PRAY", "PILGRIM"],
  pillars: ["SALAH", "ZAKAT", "SAWM", "HAJJ", "FAITH", "PRAYER", "GIVE", "FAST"],
  default: ["SALAH", "QURAN", "MOSQUE", "KIND", "LEARN", "SHARE", "PRAY", "FAITH"],
};

function getThemeWords(theme: string): string[] {
  const lower = theme.toLowerCase();

  for (const [key, words] of Object.entries(THEME_WORD_BANK)) {
    if (lower.includes(key)) {
      return words.slice(0, 7);
    }
  }

  // Build custom word list: theme word + default Islamic words
  const themeWord = theme.toUpperCase().replace(/[^A-Z]/g, "").slice(0, 7);
  const result = themeWord.length >= 3 ? [themeWord] : [];
  const defaults = THEME_WORD_BANK.default;

  for (const w of defaults) {
    if (result.length >= 7) break;
    if (!result.includes(w)) result.push(w);
  }

  return result;
}

function drawWordSearch(doc: PDFKit.PDFDocument, theme: string) {
  doc
    .fontSize(18)
    .font("Helvetica-Bold")
    .fillColor("#333333")
    .text(`Word Search: ${theme}`, { align: "center" });
  doc.moveDown(0.4);

  const words = getThemeWords(theme);

  doc
    .fontSize(11)
    .font("Helvetica")
    .fillColor("#666666")
    .text("Find these Islamic words in the grid:", { align: "center" });
  doc.moveDown(0.3);
  doc
    .fontSize(11)
    .font("Helvetica-Bold")
    .fillColor("#0d9488")
    .text(words.join("   "), { align: "center" });
  doc.moveDown(0.8);
  doc.fillColor("#000000");

  const gridSize = 13;
  const cellSize = 30;
  const startX = (595 - gridSize * cellSize) / 2;
  const startY = doc.y + 10;

  const grid = createWordSearchGrid(gridSize, words);

  doc.font("Courier-Bold").fontSize(14);

  for (let r = 0; r < gridSize; r++) {
    for (let c = 0; c < gridSize; c++) {
      const x = startX + c * cellSize;
      const y = startY + r * cellSize;

      doc.strokeColor("#e5e0d8").lineWidth(0.5).rect(x, y, cellSize, cellSize).stroke();
      doc.fillColor("#333333").text(grid[r][c], x, y + 8, {
        width: cellSize,
        align: "center",
      });
    }
  }

  // Name field below grid
  const afterGrid = startY + gridSize * cellSize + 20;
  doc
    .fontSize(10)
    .font("Helvetica")
    .fillColor("#999999")
    .text(
      "Name: _______________________    Date: _______________",
      50,
      afterGrid,
      { width: 495, align: "center" }
    );
}

function createWordSearchGrid(size: number, words: string[]): string[][] {
  const grid: string[][] = Array.from({ length: size }, () =>
    Array.from({ length: size }, () => "")
  );

  const directions = [
    [0, 1],
    [1, 0],
    [1, 1],
    [0, -1],
    [-1, 0],
  ];

  let seed = 42 + words.length;
  function random() {
    seed = (seed * 16807 + 0) % 2147483647;
    return (seed - 1) / 2147483646;
  }

  for (const word of words) {
    let placed = false;
    for (let attempt = 0; attempt < 200 && !placed; attempt++) {
      const dir = directions[Math.floor(random() * directions.length)];
      const r = Math.floor(random() * size);
      const c = Math.floor(random() * size);

      if (canPlace(grid, word, r, c, dir[0], dir[1], size)) {
        for (let i = 0; i < word.length; i++) {
          grid[r + i * dir[0]][c + i * dir[1]] = word[i];
        }
        placed = true;
      }
    }
  }

  const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      if (!grid[r][c]) {
        grid[r][c] = letters[Math.floor(random() * 26)];
      }
    }
  }

  return grid;
}

function canPlace(
  grid: string[][],
  word: string,
  r: number,
  c: number,
  dr: number,
  dc: number,
  size: number
): boolean {
  for (let i = 0; i < word.length; i++) {
    const nr = r + i * dr;
    const nc = c + i * dc;
    if (nr < 0 || nr >= size || nc < 0 || nc >= size) return false;
    if (grid[nr][nc] && grid[nr][nc] !== word[i]) return false;
  }
  return true;
}

// ── Shared drawing helpers ─────────────────────────────────────

function drawStar(
  doc: PDFKit.PDFDocument,
  cx: number,
  cy: number,
  outerR: number,
  innerR: number,
  points: number,
  color: string
) {
  doc.strokeColor(color).lineWidth(1.5);
  const step = Math.PI / points;

  const coords: { x: number; y: number }[] = [];
  for (let i = 0; i < 2 * points; i++) {
    const r = i % 2 === 0 ? outerR : innerR;
    const angle = i * step - Math.PI / 2;
    coords.push({
      x: cx + Math.cos(angle) * r,
      y: cy + Math.sin(angle) * r,
    });
  }

  doc.moveTo(coords[0].x, coords[0].y);
  for (let i = 1; i < coords.length; i++) {
    doc.lineTo(coords[i].x, coords[i].y);
  }
  doc.lineTo(coords[0].x, coords[0].y);
  doc.stroke();
}
