import type {
  AssetType,
  LiabilityType,
  MetalPriceSourceType,
  NisabBasis,
  ZakatMethodology,
} from '@/generated/prisma/client'

/**
 * Domain types for the Zakat engine.
 *
 * Everything here is plain data. The engine takes these in and returns a result;
 * it never touches Prisma, the clock, the network, or an AI provider. That is
 * what makes a calculation reproducible and what lets the whole pipeline be
 * tested without a database.
 */

/** Bumped when a change to the engine could alter a number it produces (§17). */
export const ENGINE_VERSION = 'zakat-engine@1'

// ── Inputs ───────────────────────────────────────────────────────────────────

export interface RuleSetSnapshot {
  id: string
  version: string
  name: string
  methodology: ZakatMethodology
  /** Fraction, e.g. "0.025". */
  zakatRate: string
  goldNisabGrams: string
  silverNisabGrams: string
  allowLiabilityDeduction: boolean
  assetRules: Map<AssetType, AssetRuleSnapshot>
  liabilityRules: Map<LiabilityType, LiabilityRuleSnapshot>
}

export interface AssetRuleSnapshot {
  assetType: AssetType
  zakatable: boolean
  /** 0–100, as a decimal string. */
  defaultZakatablePercentage: string
  rationale: string | null
}

export interface LiabilityRuleSnapshot {
  liabilityType: LiabilityType
  deductibleByDefault: boolean
  maxMonthsAhead: number | null
  rationale: string | null
}

export interface AssetInput {
  id: string
  type: AssetType
  name: string
  /** Decimal string in `currency`. */
  value: string
  currency: string
  /** User override of the ruleset default, 0–100. Null = follow the ruleset. */
  zakatablePercentage: string | null
  /** Present for metals entered by weight. */
  weightGrams: string | null
}

export interface LiabilityInput {
  id: string
  type: LiabilityType
  name: string
  amount: string
  currency: string
  dueDate: Date | null
  /** User override. Null = follow the ruleset. */
  deductibleForZakat: boolean | null
}

export interface MetalPriceSnapshot {
  pricePerGram: string
  currency: string
  provider: string
  sourceType: MetalPriceSourceType
  observedAt: Date
}

export interface FxRateSnapshot {
  from: string
  to: string
  rate: string
  provider: string
  observedAt: Date
}

/** Keyed `FROM/TO`. Built once per calculation; the engine only reads it. */
export type FxTable = ReadonlyMap<string, FxRateSnapshot>

export interface NisabInput {
  basis: NisabBasis
  currency: string
  ruleSet: RuleSetSnapshot
  /** Required for GOLD and SILVER. */
  metalPrice?: MetalPriceSnapshot
  /** Required for CUSTOM; a decimal string in `currency`. */
  customValue?: string | null
}

export interface NisabResult {
  basis: NisabBasis
  currency: string
  /** Minor units. */
  valueMinor: number
  metalWeightGrams: string | null
  pricePerGram: string | null
  priceProvider: string | null
  priceSourceType: MetalPriceSourceType | null
  priceObservedAt: Date | null
  /** True when the user typed the value rather than a provider supplying it. */
  manual: boolean
}

export interface ZakatEngineInput {
  calculationDate: Date
  currency: string
  methodology: ZakatMethodology
  ruleSet: RuleSetSnapshot
  assets: readonly AssetInput[]
  liabilities: readonly LiabilityInput[]
  nisab: NisabResult
  fx: FxTable
  /** From the profile: when false, no liability is deducted at all. */
  deductLiabilities: boolean
  /** Metal price used to value holdings entered by weight. */
  goldPrice?: MetalPriceSnapshot
  silverPrice?: MetalPriceSnapshot
}

// ── Output ───────────────────────────────────────────────────────────────────

export type ResultItemKind = 'ASSET' | 'LIABILITY'

/**
 * One line of the explanation (§13).
 *
 * The engine emits structured items; no layer below the UI ever builds a
 * sentence, so the same data drives the review screen, the stored snapshot and
 * (later) an AI restatement of it.
 */
export interface ResultItem {
  kind: ResultItemKind
  sourceEntityId: string
  label: string
  type: AssetType | LiabilityType

  /** Contribution to the total, in minor units of the calculation currency. */
  amountMinor: number

  /** As entered, before conversion. */
  originalAmount: string
  originalCurrency: string
  exchangeRate: string | null

  /** Applied share, 0–100. Null for liabilities. */
  zakatablePercentage: string | null

  included: boolean
  /** Why it counted or did not — shown verbatim, never generated by AI. */
  reason: string
  /** Which rule decided this, for the sources section of the UI. */
  ruleBasis: string
}

export interface ZakatCalculationResult {
  currency: string
  calculationDate: Date
  engineVersion: string

  ruleSetId: string
  rulesVersion: string
  methodology: ZakatMethodology

  grossZakatableAssetsMinor: number
  deductibleLiabilitiesMinor: number
  netZakatableWealthMinor: number

  nisab: NisabResult
  aboveNisab: boolean

  /** Fraction, e.g. "0.025". */
  zakatRate: string
  zakatDueMinor: number

  items: readonly ResultItem[]
  /** Every rate actually used, for the snapshot and the sources section. */
  ratesUsed: readonly FxRateSnapshot[]
}

export function fxKey(from: string, to: string): string {
  return `${from.toUpperCase()}/${to.toUpperCase()}`
}
